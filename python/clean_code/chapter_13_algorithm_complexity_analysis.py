#  * `s[i] reading и s[i] = value assignment` — операции O(1).  
#  * `s.append(value)` — операция O(1).  
#  * `s.insert(i, value)` — операция  O($ \textit{n} $). Вставка значения в последовательность (особенно в начало) требует сдвига всех элементов с индексами выше i на одну позицию вверх в последовательности.  
#  * `s.remove(value)` — операция O($ \textit{n} $). Удаление значений из последовательности (особенно в начале) требует сдвига всех элементов с индексами выше i на одну позицию вниз в последовательности.  
#  * `s.reverse()` — операция O($ \textit{n} $), потому что необходимо переставить все элементы последовательности.  
#  * `s.sort()` — операция O($ \textit{n} $ log $ \textit{n} $), потому что алгоритм сортировки Python имеет сложность O($ \textit{n} $ log $ \textit{n} $).  
#  * `value in s` — операция O($ \textit{n} $), потому что необходимо проверить каждый элемент.  
#  * `for value in s:` — операция O($ \textit{n} $).  
#  * `len(s)` — операция O(1), потому что Python хранит количество элементов в последовательности, чтобы их не приходилось заново пересчитывать при каждом вызове `len()`.  


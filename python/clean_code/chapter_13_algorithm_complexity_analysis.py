# ### Моментальный анализ сложности  

# Если обозначить переменной n размер данных, с которыми работает код, можно воспользоваться рядом общих правил:  
#  - Если код не обращается ни к каким данным, это O(1).
#  - Если код последовательно перебирает данные, это O(1).
#  - Если код содержит два вложенных цикла, каждый из которых перебирает данные, это O($ n^2 $).
#  - Если код содержит операцию «разделяй и властвуй», которая многократно делит данные надвое, это O(log $ \textit{n} $).
#  - Если код содержит операцию «разделяй и властвуй», которая выполняется по одному разу для каждого элемента данных, это O($ \textit{n} $ log $ \textit{n} $).
#  - Если код перебирает все возможные комбинации значений в данных с размером $ \textit{n} $, это O($ 2^n $) или другой экспоненциальный порядок.
#  - Если код перебирает все возможные перестановки (то есть варианты упорядочения) значений данных, это O($ \textit{n} $!).
#  - Если код включает сортировку данных, это как минимум O($ \textit{n} $ log $ \textit{n} $)

# Нотация «О-большое» полезна прежде всего при большом объеме обрабатываемых данных. В реальных ситуациях объем данных обычно невелик.  



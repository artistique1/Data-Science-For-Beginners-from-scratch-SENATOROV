# ### Анализ алгоритмов с использованием нотации «O-большое»  

# `Нотация «О-большое»` — метод анализа алгоритмов, описывающий масштабирование времени выполнения кода. Код классифицируется по нескольким порядкам сложности, каждый из которых в общем виде показывает, насколько увеличится время выполнения кода при возрастании объема выполняемой работы.  

# ##### Порядки нотации «О-большое»  

# Нотация «О-большое» обычно определяет несколько `порядков сложности`. По возрастанию:  
#    1. O(1), постоянное время (самый низкий порядок).  
#    2. O(log $ \textit{n} $), логарифмическое время.  
#    3. O($ \textit{n} $), линейное время.  
#    4. O($ \textit{n} $ log $ \textit{n} $), время N-Log-N.  
#    5. O($ n^2 $), полиномиальное время.  
#    6. O($ 2^n $), экспоненциальное время.  
#    7. O($ \textit{n} $!), факториальное время (наивысший порядок).  

# Буква $ \textit{n} $ в скобках представляет размер входных данных, с которыми работает код.  

#   * O(1) и O(log $ \textit{n} $) — быстрые алгоритмы.  
#   * O($ \textit{n} $) и O($ \textit{n} $ log $ \textit{n} $) — неплохие алгоритмы.  
#   * O($ n^2 $), O($ 2^n $) и O($ \textit{n} $!) — медленные алгоритмы.  

# **O(1)** означает, что алгоритм выполняется за константное время, независимо от размера входных данных. O(1) — это "золотой стандарт" для алгоритмов, так как они выполняются мгновенно, независимо от объема данных.  

# **O(log $ \textit{n} $)** — это алгоритм `бинарного поиска`. Алгоритмы log $ \textit{n} $ обычно включают принцип «разделяй и властвуй», который выбирает половину входных данных размера $ \textit{n} $, потом половину от этой половины и т. д. Операции log $ \textit{n} $ хорошо масштабируются: рабочая нагрузка $ \textit{n} $ возрастает вдвое, тогда как время выполнения увеличивается всего на один шаг.  

# **O($ \textit{n} $)** означает, что время выполнения алгоритма линейно зависит от размера входных данных. Алгоритмы с O($ \textit{n} $) сложностью считаются эффективными для задач, где нужно обработать каждый элемент входных данных.  

# **O($ \textit{n} $ log $ \textit{n} $), время N-Log-N**. Можно рассматривать задачу O($ \textit{n} $ log $ \textit{n} $) как задачу O(log $ \textit{n} $), которую необходимо выполнить $ \textit{n} $ раз, то есть время выполнения алгоритма пропорционально произведению размера входных данных ($ \textit{n} $) на логарифм этого размера (log $ \textit{n} $). Алгоритмы этой сложности считаются очень эффективными для задач, где нужно обработать большие объемы данных. Все эффективные обобщенные алгоритмы сортировки имеют порядок O($ \textit{n} $ log $ \textit{n} $): сортировка слиянием, быстрая сортировка, пирамидальная сортировка и Timsort (алгоритм Timsort, изобретенный Тимом Петерсом (Tim Peters), используется методом Python `sort()`)

# **O($ n^2 $)** означает, что время выполнения алгоритма пропорционально квадрату размера входных данных. Порядок O($ n^2 $) обычно становится переломной точкой для существенного замедления алгоритмов. Когда вы осознаете, что ваш код выполняется со временем O($ n^2 $) и выше, стоит сделать паузу. Время O($ n^2 $) также называют `квадратичным`. Кроме того, известны алгоритмы с временем O($ n^3 $), или `кубическим` временем, которое медленнее O($ n^2 $); алгоритмы с временем O($ n^4 $), или `биквадратным` временем, которое медленнее O($ n^3 $), и другие варианты полиномиальной сложности.  

# **O($ 2^n $)** означает, что время выполнения алгоритма экспоненциально растет в зависимости от размера входных данных. Это один из самых неэффективных уровней сложности, и такие алгоритмы считаются непрактичными для задач с большими объемами данных.

# **O($ \textit{n} $!)** означает, что время выполнения алгоритма растет пропорционально факториалу размера входных данных. Это один из самых медленных уровней сложности, и такие алгоритмы так же считаются непрактичными для задач даже с небольшими объемами данных. Факториал числа равен произведению всех положительных целых чисел вплоть до этого числа. Среди задач со временем 
# O($ \textit{n} $!) хорошо известна задача о коммивояжере. Коммивояжер должен посетить n городов; он хочет вычислить суммарное расстояние для всех $ \textit{n} $! возможных вариантов их посещения. По результатам вычислений он рассчитывает определить вариант с кратчайшим расстоянием. При большом количестве городов завершить перебор за разумное время не удастся.  


# ###  «О-большое» как оценка худшего сценария  

# `«О-большое»` оценивает `худший сценарий` для любой задачи. Нотация `«О-большое»` описывает, что происходит, если вам не повезет.  

# Некоторые программисты также используют нотацию `«Омега-большое»`, описывающую лучший сценарий для алгоритма. Например, алгоритм $\Omega$($ \textit{n} $) в лучшем случае работает с линейной эффективностью, в худшем - он может работать медленнее.  

# Нотация `«Тэта-большое»` описывает алгоритмы с одинаковыми порядками в лучшем и худшем случае. Например, |$\Theta$($ \textit{n} $) описывает алгоритм с линейной эффективностью в лучшем и худшем случае — то есть алгоритм O($ \textit{n} $) и $\Omega$($ \textit{n} $).  


# ### Определение порядка сложности нотации «О-большое» вашего кода  

# Чтобы определить порядок сложности нотации «О-большое» для фрагмента кода, необходимо решить четыре задачи: 
#   1. определить $ \textit{n} $  
#   2. подсчитать шаги в коде  
#   3. исключить нижние порядки  
#   4. исключить коэффициенты  

# #### Почему низкие порядки и коэффициенты не важны?  

# Низкие порядки исключаются из подсчета шагов, потому что они становятся менее значимыми с увеличением размера $ \textit{n} $. 
# При увеличении объема данных большой коэффициент меньшего порядка может игнорироваться по сравнению с высокими порядками. При определенном размере $ \textit{n} $ более высокие порядки всегда будут медленнее низких порядков.  


